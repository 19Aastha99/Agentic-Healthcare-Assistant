import requests, xml.etree.ElementTree as ET, time

def search_pubmed(query, max_results=5):
    base = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/"
    try:
        search_url = base + "esearch.fcgi"
        sr = requests.get(search_url, params={
            "db":"pubmed", "term":query, "retmax":max_results,
            "sort":"date", "retmode":"json"
        }, timeout=20)
        sr.raise_for_status()
        ids = sr.json().get("esearchresult",{}).get("idlist",[])
        if not ids:
            return []
        fetch = requests.get(base+"efetch.fcgi", params={
            "db":"pubmed", "id":",".join(ids), "retmode":"xml"
        }, timeout=30)
        fetch.raise_for_status()
        root = ET.fromstring(fetch.text)
        docs = []
        for article in root.findall(".//PubmedArticle"):
            pmid = article.findtext(".//PMID", default="")
            title = "".join(article.find(".//ArticleTitle").itertext()) if article.find(".//ArticleTitle") is not None else "Untitled"
            abstract_parts = []
            for node in article.findall(".//Abstract/AbstractText"):
                label = node.attrib.get("Label","")
                txt = "".join(node.itertext())
                abstract_parts.append((label + ": " if label else "") + txt)
            abstract = " ".join(abstract_parts)
            if abstract:
                docs.append({
                    "title":title, "abstract":abstract, "pmid":pmid,
                    "url":f"https://pubmed.ncbi.nlm.nih.gov/{pmid}/"
                })
        log_event("research", "pubmed_search", "success", f"{len(docs)} articles for {query}")
        return docs
    except Exception as e:
        log_event("research", "pubmed_search", "failed", str(e))
        print("PubMed retrieval issue:", e)
        return []

