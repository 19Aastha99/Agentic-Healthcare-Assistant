def calculate_metrics():
    logs = show_table("SELECT module, action, status FROM agent_logs")
    total = len(logs)
    success = int((logs["status"]=="success").sum()) if total else 0
    booking_attempts = int((logs["action"]=="book_appointment").sum()) if total else 0
    booking_success = int(((logs["action"]=="book_appointment") & (logs["status"]=="success")).sum()) if total else 0
    return {
        "total_logged_events":total,
        "successful_events":success,
        "tool_success_rate_percent":round(100*success/total,2) if total else 0,
        "booking_attempts":booking_attempts,
        "successful_bookings":booking_success,
        "booking_success_rate_percent":round(100*booking_success/booking_attempts,2) if booking_attempts else 0
    }

