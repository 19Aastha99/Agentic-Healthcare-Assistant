def find_patient(query):
    conn = get_conn()
    rows = conn.execute("SELECT * FROM patients").fetchall()
    conn.close()
    q = query.lower()
    for r in rows:
        if r["patient_id"].lower() in q or r["name"].lower() in q:
            return dict(r)
    # Demo fallback: if the request says father, return the synthetic father record
    if "father" in q or "dad" in q:
        conn = get_conn()
        r = conn.execute("SELECT * FROM patients WHERE patient_id='P1001'").fetchone()
        conn.close()
        return dict(r) if r else None
    return None

def get_patient_history(patient_id):
    conn = get_conn()
    rows = conn.execute(
        "SELECT entry_date, category, details FROM medical_history WHERE patient_id=? ORDER BY entry_date",
        (patient_id,)).fetchall()
    conn.close()
    return [dict(r) for r in rows]

def list_doctors(specialty=None):
    conn = get_conn()
    if specialty:
        rows = conn.execute("SELECT * FROM doctors WHERE lower(specialty) LIKE ?",
                            (f"%{specialty.lower()}%",)).fetchall()
    else:
        rows = conn.execute("SELECT * FROM doctors").fetchall()
    conn.close()
    return [dict(r) for r in rows]

def book_appointment(patient_id, specialty):
    doctors = list_doctors(specialty)
    if not doctors:
        log_event("appointment", "doctor_search", "not_found", specialty)
        return {"status":"not_found", "message":f"No doctor found for specialty: {specialty}"}
    conn = get_conn()
    doctor = doctors[0]
    slot = conn.execute(
        "SELECT * FROM slots WHERE doctor_id=? AND is_booked=0 ORDER BY slot_time LIMIT 1",
        (doctor["doctor_id"],)).fetchone()
    if not slot:
        conn.close()
        log_event("appointment", "slot_search", "unavailable", specialty)
        return {"status":"unavailable", "message":"No available slots were found."}
    # Atomic update protects against double booking in this small demo
    cur = conn.execute("UPDATE slots SET is_booked=1 WHERE slot_id=? AND is_booked=0",
                       (slot["slot_id"],))
    if cur.rowcount != 1:
        conn.rollback()
        conn.close()
        return {"status":"conflict", "message":"That slot was just taken. Please try again."}
    appt_id = "APT-" + str(uuid.uuid4())[:8].upper()
    conn.execute("INSERT INTO appointments VALUES (?,?,?,?,?,?)",
                 (appt_id, patient_id, doctor["doctor_id"], slot["slot_id"],
                  "BOOKED", datetime.datetime.now().isoformat(timespec="seconds")))
    conn.commit()
    conn.close()
    result = {"status":"booked", "appointment_id":appt_id,
              "doctor":doctor["name"], "specialty":doctor["specialty"],
              "slot_time":slot["slot_time"]}
    log_event("appointment", "book_appointment", "success", result)
    return result

