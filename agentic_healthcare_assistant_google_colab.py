from typing import TypedDict, Any
from langgraph.graph import StateGraph, END

class AssistantState(TypedDict, total=False):
    user_query: str
    patient: Any
    history: Any
    need_appointment: bool
    need_research: bool
    specialty: str
    appointment: Any
    research_query: str
    sources: Any
    retrieved_context: Any
    plan: Any
    response: str
    trace: Any

def planner_node(state: AssistantState):
    q = state["user_query"]
    low = q.lower()
    need_appt = any(w in low for w in ["book", "appointment", "schedule", "consult"])
    need_research = any(w in low for w in ["treatment", "latest", "research", "information", "explain", "disease"])
    specialty = "nephrologist" if any(w in low for w in ["kidney", "renal", "nephro"]) else (
        "cardiologist" if any(w in low for w in ["heart", "cardio"]) else "")
    patient = find_patient(q)
    plan = []
    if patient:
        plan += ["Identify patient", "Retrieve medical history"]
    if need_appt:
        plan += ["Find doctor and available slot", "Book appointment"]
    if need_research:
        plan += ["Search PubMed", "Retrieve relevant abstracts using FAISS", "Generate evidence-grounded summary"]
    log_event("planner", "decompose_goal", "success", plan)
    return {"patient":patient, "need_appointment":need_appt,
            "need_research":need_research, "specialty":specialty,
            "research_query":q, "plan":plan, "trace":["Planner: "+", ".join(plan)]}

def records_node(state: AssistantState):
    patient = state.get("patient")
    if not patient:
        return {"history":[], "trace":state.get("trace",[])+["Records: patient not identified"]}
    hist = get_patient_history(patient["patient_id"])
    log_event("records", "retrieve_history", "success", patient["patient_id"])
    return {"history":hist, "trace":state.get("trace",[])+["Records: retrieved patient history"]}

def appointment_node(state: AssistantState):
    if not state.get("need_appointment"):
        return {"appointment":{"status":"not_requested"},
                "trace":state.get("trace",[])+["Appointment: not requested"]}
    patient = state.get("patient")
    if not patient:
        return {"appointment":{"status":"needs_patient",
                "message":"Please provide a registered patient name or ID before booking."},
                "trace":state.get("trace",[])+["Appointment: patient identification required"]}
    specialty = state.get("specialty")
    if not specialty:
        return {"appointment":{"status":"needs_specialty",
                "message":"Please specify the required doctor specialty."},
                "trace":state.get("trace",[])+["Appointment: specialty clarification required"]}
    result = book_appointment(patient["patient_id"], specialty)
    return {"appointment":result,
            "trace":state.get("trace",[])+["Appointment: "+result["status"]]}

def research_node(state: AssistantState):
    if not state.get("need_research"):
        return {"sources":[], "retrieved_context":[],
                "trace":state.get("trace",[])+["Research: not requested"]}
    docs = search_pubmed(state.get("research_query","medical information"), max_results=8)
    count = build_medical_index(docs)
    hits = retrieve_medical_context(state.get("research_query",""), k=3) if count else []
    sources = [{"title":d["title"],"url":d["url"],"pmid":d["pmid"]} for d in docs]
    context = [{"text":d.page_content, "metadata":d.metadata} for d in hits]
    return {"sources":sources, "retrieved_context":context,
            "trace":state.get("trace",[])+[f"Research: {len(docs)} PubMed articles; {len(hits)} FAISS matches"]}

def response_node(state: AssistantState):
    try:
        from langchain_groq import ChatGroq
        llm = ChatGroq(model=GROQ_MODEL, temperature=0.1, api_key=os.environ["GROQ_API_KEY"])
        patient = state.get("patient")
        prompt = f'''
You are an educational healthcare administration assistant.
Do not diagnose, prescribe, recommend a medication dose, or claim that a treatment is suitable for this individual.
Encourage consultation with a qualified clinician. If symptoms suggest an emergency, advise contacting local emergency services.
Use only the supplied patient record and retrieved literature for factual claims. Say when information is missing.
Do not invent sources. Cite retrieved PubMed titles and URLs when available.

USER REQUEST:
{state.get("user_query")}

PATIENT RECORD:
{json.dumps(patient, default=str)}

PAST HISTORY:
{json.dumps(state.get("history",[]), default=str)}

APPOINTMENT RESULT:
{json.dumps(state.get("appointment",{}), default=str)}

RETRIEVED MEDICAL LITERATURE:
{json.dumps(state.get("retrieved_context",[]), default=str)}

PUBMED SOURCES:
{json.dumps(state.get("sources",[]), default=str)}

PLANNING TRACE:
{json.dumps(state.get("plan",[]), default=str)}

Write a clear response with sections: Patient context, Appointment, Medical information, and Important note. Omit irrelevant sections.
'''
        answer = llm.invoke(prompt).content
    except Exception as e:
        answer = ("The workflow completed, but LLM response generation failed. "
                  "Check the Groq API key/model and retry. Technical detail: " + str(e))
    log_event("response", "generate_response", "success", "Response generated")
    return {"response":answer, "trace":state.get("trace",[])+["Response: generated"]}

