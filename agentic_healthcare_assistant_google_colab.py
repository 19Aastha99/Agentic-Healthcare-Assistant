from langchain_community.vectorstores import FAISS

embeddings = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")
vector_store = None

def build_medical_index(docs):
    global vector_store
    if not docs:
        vector_store = None
        return 0
    lang_docs = [
        Document(
            page_content=d["title"] + "\n" + d["abstract"],
            metadata={"title":d["title"], "pmid":d["pmid"], "url":d["url"]}
        ) for d in docs
    ]
    vector_store = FAISS.from_documents(lang_docs, embeddings)
    vector_store.save_local("/content/medical_faiss_index")
    return len(lang_docs)

def retrieve_medical_context(question, k=3):
    if vector_store is None:
        return []
    return vector_store.similarity_search(question, k=k)

